"""Export deterministic PostgreSQL schema SQL for local-development bootstrap."""

from __future__ import annotations

import sys
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SRC_ROOT = PROJECT_ROOT / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

import humbee_sfa.models_registry  # noqa: F401
from humbee_sfa.core.db import Base

OUTPUT_PATH = PROJECT_ROOT / "db" / "bootstrap" / "01_schema.sql"


def _render_statement(statement: object) -> str:
    dialect = postgresql.dialect()
    compiled = statement.compile(dialect=dialect)
    return f"{compiled};"


def _table_create_statements() -> list[str]:
    statements: list[str] = []
    for table in Base.metadata.sorted_tables:
        statements.append(_render_statement(CreateTable(table)))
    return statements


def _index_create_statements() -> list[str]:
    statements: list[str] = []
    for table in Base.metadata.sorted_tables:
        for index in sorted(table.indexes, key=lambda item: item.name or ""):
            statements.append(_render_statement(CreateIndex(index)))
    return statements


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    statements = [
        "-- Generated by scripts/export_dev_schema_sql.py",
        "-- Re-run this script whenever ORM metadata changes.",
        "",
    ]
    statements.extend(_table_create_statements())
    statements.append("")
    statements.extend(_index_create_statements())
    statements.append("")

    OUTPUT_PATH.write_text("\n".join(statements), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
